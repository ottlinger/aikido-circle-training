  function createTranslator(language = 'de') {
    const locale = Object.hasOwn(translations, language) ? language : 'de';
    const messages = translations[locale];
    const formatter = new Intl.NumberFormat(locale);
    return {
      language: locale,
      number: (value) => formatter.format(value),
      t(key, parameters = {}) {
        if (!Object.hasOwn(messages, key)) throw new Error(`Unknown translation key: ${key}`);
        return messages[key].replace(/\{(\w+)\}/g, (_, name) => {
          if (!Object.hasOwn(parameters, name)) throw new Error(`Missing translation parameter: ${key}.${name}`);
          return String(parameters[name]);
        });
      },
    };
  }

